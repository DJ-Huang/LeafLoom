const assert = require('node:assert/strict');
require('../vault_rag/design_assets/studio/runtime.js');
const project = globalThis.LeafLoomStudio.projectDocument;
const source = {id:'p', bindings:{headline:{key:'headline',kind:'text',value:'Source',revision:2},hero:{key:'hero',kind:'image',value:'asset-a',revision:1}}, variants:{ja:{id:'ja',values:{headline:{value:'翻訳',sourceRevision:1},hero:{value:'asset-b',sourceRevision:1}},layout:{title:{fontSize:20}},pageLayout:{home:{width:600}}}},components:{card:{node:{id:'component-title',type:'text',props:{bindingKey:'headline',text:'original'}}}},pages:[{id:'home',width:800,height:600,nodes:[{id:'title',type:'text',props:{text:'original',bindingKey:'headline'},style:{fontSize:32,color:'red'}},{id:'image',type:'image',props:{bindingKey:'hero',assetId:'old',src:'https://example.com/old.png'}}]}]};
const before = JSON.stringify(source);
const base = project(source);
assert.equal(base.pages[0].nodes[0].props.text,'Source');
assert.equal(base.components.card.node.props.text,'Source');
assert.equal(base.pages[0].nodes[1].props.assetId,'asset-a');
assert.equal(base.pages[0].nodes[1].props.src,undefined);
const ja = project(source,'ja');
assert.equal(ja.pages[0].nodes[0].props.text,'翻訳');
assert.deepEqual(ja.pages[0].nodes[0].style,{fontSize:20,color:'red'});
assert.equal(ja.pages[0].width,600);
assert.equal(ja.components.card.node.props.text,'翻訳');
assert.equal(ja.pages[0].nodes[1].props.assetId,'asset-b');
assert.equal(JSON.stringify(source),before);
source.variants.ja.values.headline.value='';
assert.equal(project(source,'ja').pages[0].nodes[0].props.text,'');
delete source.variants.ja.values.headline;
assert.equal(project(source,'ja').pages[0].nodes[0].props.text,'Source');
assert.throws(()=>project(source,'missing'),/Unknown variant/);
console.log('Studio binding projection contracts passed.');
